/* ============================================================
   图片压缩：手机照片动辄几 MB，直接存 localStorage 会爆，
   必须先缩到目标尺寸再转 JPEG dataURL。
   ============================================================ */
const Img = {
  /* file → dataURL（cover 裁剪到 w×h） */
  compress(file, w, h, quality = 0.75) {
    return new Promise((resolve, reject) => {
      const rd = new FileReader();
      rd.onerror = () => reject(new Error('读取失败'));
      rd.onload = () => {
        const im = new Image();
        im.onerror = () => reject(new Error('不是有效的图片'));
        im.onload = () => {
          const cv = document.createElement('canvas');
          cv.width = w; cv.height = h;
          const g = cv.getContext('2d');
          // cover：按比例放大后再居中裁掉多余部分
          const s = Math.max(w / im.width, h / im.height);
          const dw = im.width * s, dh = im.height * s;
          g.drawImage(im, (w - dw) / 2, (h - dh) / 2, dw, dh);
          resolve(cv.toDataURL('image/jpeg', quality));
        };
        im.src = rd.result;
      };
      rd.readAsDataURL(file);
    });
  },
  load(src) {
    return new Promise((resolve) => {
      if (!src) return resolve(null);
      const im = new Image();
      im.onload = () => resolve(im);
      im.onerror = () => resolve(null);
      im.src = src;
    });
  },
  kb(dataUrl) { return dataUrl ? Math.round(dataUrl.length * 0.75 / 1024) : 0; },
};
