/* ============================================================
   地理计算
   ============================================================ */
const Geo = {
  /* 等距圆柱投影：经度 73-136、纬度 16-54 映射到 SVG 坐标
     （纬度下限取 16 是为了把南海诸岛的三沙也纳入范围） */
  LNG0: 73, LNG1: 136, LAT0: 54, LAT1: 16,
  KX: 10, KY: 11.5,

  x(lng) { return (lng - this.LNG0) * this.KX; },
  y(lat) { return (this.LAT0 - lat) * this.KY; },

  /* Haversine 距离（公里） */
  dist(a, b) {
    const R = 6371;
    const dLat = (b.lat - a.lat) * Math.PI / 180;
    const dLng = (b.lng - a.lng) * Math.PI / 180;
    const la1 = a.lat * Math.PI / 180, la2 = b.lat * Math.PI / 180;
    const h = Math.sin(dLat / 2) ** 2 + Math.cos(la1) * Math.cos(la2) * Math.sin(dLng / 2) ** 2;
    return 2 * R * Math.asin(Math.sqrt(h));
  },

  fmt(km) {
    if (km == null) return '—';
    if (km < 1) return '同城 · 极近';
    if (km < 100) return Math.round(km) + ' km';
    if (km < 1000) return Math.round(km / 10) * 10 + ' km';
    return (km / 1000).toFixed(1) + ' 千 km';
  },

  inRange(lng, lat) {
    return lng >= this.LNG0 && lng <= this.LNG1 && lat >= this.LAT1 && lat <= this.LAT0;
  },
};

